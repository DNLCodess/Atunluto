/**
 * PATCH  /results-portal/api/admins/state/[id]
 *   body: { action: "toggle", activate: bool }
 *   body: { action: "regenerate" }
 * DELETE /results-portal/api/admins/state/[id]  — deleteElectionAdmin
 */

import { createAdminClient } from "@/supabase/admin";
import { getResultsSession } from "@/lib/erms-session";
import { generateSecurePassword } from "@/utils/password-generator";
import { headers } from "next/headers";
import { NextResponse } from "next/server";

async function logEvent(supabase, adminId, action, ipAddress, userAgent, notes) {
  try {
    await supabase.from("result_audit_log").insert({
      action,
      table_name: "election_admins",
      performed_by: adminId,
      ip_address: ipAddress,
      user_agent: userAgent,
      notes,
    });
  } catch { /* non-fatal */ }
}

export async function PATCH(request, { params }) {
  const session = await getResultsSession();
  if (!session || session.role !== "state_admin") {
    return NextResponse.json({ error: "Unauthorised." }, { status: 401 });
  }

  const { id: adminId } = await params;
  const body = await request.json().catch(() => ({}));
  const supabase = createAdminClient();
  const hdrs = await headers();
  const ipAddress = hdrs.get("x-forwarded-for") || "unknown";
  const userAgent = hdrs.get("user-agent") || "unknown";

  if (body.action === "toggle") {
    const { activate } = body;

    if (adminId === session.id) {
      return NextResponse.json(
        { error: "You cannot change the status of your own account." },
        { status: 400 },
      );
    }

    const { error } = await supabase
      .from("election_admins")
      .update({ is_active: activate })
      .eq("id", adminId)
      .eq("role", "state_admin");

    if (error) return NextResponse.json({ error: "Failed to update account status." }, { status: 500 });

    await supabase.auth.admin.updateUserById(adminId, {
      ban_duration: activate ? "none" : "876600h",
    });

    if (!activate) await supabase.auth.admin.signOut(adminId);

    await logEvent(
      supabase,
      adminId,
      activate ? "ACCOUNT_ACTIVATED" : "ACCOUNT_DEACTIVATED",
      ipAddress,
      userAgent,
      `${activate ? "Activated" : "Deactivated"} by State Admin ${session.id}`,
    );

    return NextResponse.json({ success: true });
  }

  if (body.action === "regenerate") {
    const plainPassword = generateSecurePassword(12);

    await supabase.auth.admin.updateUserById(adminId, { password: plainPassword });

    const { error } = await supabase
      .from("election_admins")
      .update({ must_change_password: true })
      .eq("id", adminId)
      .eq("role", "state_admin");

    if (error) return NextResponse.json({ error: "Failed to regenerate password." }, { status: 500 });

    await supabase.auth.admin.signOut(adminId);

    await logEvent(
      supabase,
      adminId,
      "PASSWORD_REGENERATE",
      ipAddress,
      userAgent,
      `Regenerated by State Admin ${session.id}`,
    );

    return NextResponse.json({ success: true, plainPassword });
  }

  return NextResponse.json({ error: "Invalid action." }, { status: 400 });
}

export async function DELETE(request, { params }) {
  const session = await getResultsSession();
  if (!session || session.role !== "state_admin") {
    return NextResponse.json({ error: "Unauthorised." }, { status: 401 });
  }

  const { id: adminId } = await params;

  if (adminId === session.id) {
    return NextResponse.json(
      { error: "You cannot delete your own account." },
      { status: 400 },
    );
  }

  const supabase = createAdminClient();

  await supabase.auth.admin.signOut(adminId);

  const { error: dbError } = await supabase
    .from("election_admins")
    .delete()
    .eq("id", adminId);

  if (dbError) return NextResponse.json({ error: "Failed to delete account." }, { status: 500 });

  await supabase.auth.admin.deleteUser(adminId);

  return NextResponse.json({ success: true });
}
